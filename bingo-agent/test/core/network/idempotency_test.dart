import 'package:bingo_agent/src/core/network/idempotency.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('returns a stable key until explicitly regenerated by callers', () {
    final key = IdempotencyKeyStore.newKey();
    final sameKey = IdempotencyKeyStore.newKey();

    expect(key, isNotEmpty);
    expect(sameKey, isNotEmpty);
    expect(key, isNot(equals(sameKey)));
  });
}