create table bingo_agents (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    status varchar(20) not null,
    city varchar(80) not null,
    territory varchar(120) not null,
    id_document_type varchar(40) not null,
    id_document_number varchar(80) not null,
    id_document_front_reference varchar(200),
    id_document_back_reference varchar(200),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint not null default 0,
    constraint fk_bingo_agents_user foreign key (user_id) references users (id),
    constraint uk_bingo_agents_user unique (user_id)
);

create table agent_floats (
    id bigint generated by default as identity primary key,
    agent_id bigint not null,
    currency varchar(3) not null,
    available_balance decimal(19,2) not null,
    clearing_balance decimal(19,2) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint not null default 0,
    constraint fk_agent_floats_agent foreign key (agent_id) references bingo_agents (id),
    constraint uk_agent_floats_agent unique (agent_id)
);

create table agent_float_transactions (
    id bigint generated by default as identity primary key,
    agent_float_id bigint not null,
    transaction_type varchar(50) not null,
    amount decimal(19,2) not null,
    available_before decimal(19,2) not null,
    available_after decimal(19,2) not null,
    clearing_before decimal(19,2) not null,
    clearing_after decimal(19,2) not null,
    related_entity_type varchar(80) not null,
    related_entity_id bigint,
    operation_id varchar(36) not null,
    note varchar(500),
    created_at timestamp(6) not null,
    constraint fk_agent_float_transactions_float foreign key (agent_float_id) references agent_floats (id),
    constraint uk_agent_float_transactions_operation unique (operation_id)
);

create table commission_rules (
    id bigint generated by default as identity primary key,
    version_number int not null,
    commission_rate_bps int not null,
    active boolean not null,
    effective_from timestamp(6) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_commission_rules_version unique (version_number)
);

create table commission_accruals (
    id bigint generated by default as identity primary key,
    agent_id bigint not null,
    ticket_id bigint not null,
    session_id bigint not null,
    commission_rule_id bigint not null,
    commission_rule_version int not null,
    sale_amount decimal(19,2) not null,
    commission_amount decimal(19,2) not null,
    status varchar(20) not null,
    operation_id varchar(36) not null,
    created_at timestamp(6) not null,
    settled_at timestamp(6),
    settlement_reference varchar(120),
    settlement_note varchar(500),
    constraint fk_commission_accruals_agent foreign key (agent_id) references bingo_agents (id),
    constraint fk_commission_accruals_ticket foreign key (ticket_id) references bingo_tickets (id),
    constraint fk_commission_accruals_session foreign key (session_id) references bingo_sessions (id),
    constraint fk_commission_accruals_rule foreign key (commission_rule_id) references commission_rules (id),
    constraint uk_commission_accruals_ticket unique (ticket_id),
    constraint uk_commission_accruals_operation unique (operation_id)
);

create table agent_float_top_up_requests (
