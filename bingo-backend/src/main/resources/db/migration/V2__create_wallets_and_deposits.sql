create table wallets (
    id bigint generated by default as identity primary key,
    owner_id bigint not null,
    currency varchar(3) not null,
    available_balance decimal(19, 2) not null,
    version bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_wallets_owner unique (owner_id),
    constraint fk_wallets_owner foreign key (owner_id) references users (id)
);

create table wallet_transactions (
    id bigint generated by default as identity primary key,
    wallet_id bigint not null,
    operation_id varchar(36) not null,
    transaction_type varchar(40) not null,
    amount decimal(19, 2) not null,
    balance_before decimal(19, 2) not null,
    balance_after decimal(19, 2) not null,
    currency varchar(3) not null,
    reference_type varchar(40),
    reference_id bigint,
    note varchar(500),
    created_at timestamp(6) not null,
    constraint fk_wallet_transactions_wallet foreign key (wallet_id) references wallets (id)
);

create index idx_wallet_transactions_wallet_created_at on wallet_transactions (wallet_id, created_at desc);
create index idx_wallet_transactions_operation_id on wallet_transactions (operation_id);

create table deposit_claims (
    id bigint generated by default as identity primary key,
    player_id bigint not null,
    submitted_cash_amount decimal(19, 2) not null,
    currency varchar(3) not null,
    conversion_rate_snapshot decimal(19, 6) not null,
    calculated_credit_amount decimal(19, 2) not null,
    normalized_telebirr_reference varchar(120) not null,
    status varchar(20) not null,
    submitted_at timestamp(6) not null,
    reviewed_by_user_id bigint,
    reviewed_at timestamp(6),
    review_note varchar(500),
    operation_id varchar(36) not null,
    constraint uk_deposit_claims_reference unique (normalized_telebirr_reference),
    constraint fk_deposit_claims_player foreign key (player_id) references users (id),
    constraint fk_deposit_claims_reviewed_by foreign key (reviewed_by_user_id) references users (id)
);

create index idx_deposit_claims_player_submitted_at on deposit_claims (player_id, submitted_at desc);
create index idx_deposit_claims_status on deposit_claims (status);
create index idx_deposit_claims_operation_id on deposit_claims (operation_id);

create table idempotency_records (
    idempotency_key varchar(80) primary key,
    request_hash varchar(64) not null,
    response_status int not null,
    response_body longtext not null,
    operation_id varchar(36) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null
);
